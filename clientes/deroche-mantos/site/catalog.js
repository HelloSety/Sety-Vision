function pixOf(p) { return priceOf(p) * 0.95; }
function installOf(p) { return priceOf(p) / 12; }

function waLink(id) {
  const p = PRODUCTS[id];
  const msg = `Olá! Tenho interesse neste produto:\n*${p.name}*\nValor: ${fmtBRL(priceOf(p))}\nPode me enviar mais informações?`;
  return `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(msg)}`;
}

